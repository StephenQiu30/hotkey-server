        ) THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'document_version_readable_artifact', MESSAGE = 'readable document version requires an active healthy retained artifact';
        END IF;
    END IF;
    IF NOT (
        OLD.lifecycle_state = 'policy_pending' AND NEW.lifecycle_state IN ('policy_blocked','derive_pending','quarantined')
        OR OLD.lifecycle_state = 'derive_pending' AND NEW.lifecycle_state IN ('derived_available','derive_failed','policy_blocked','quarantined')
        OR OLD.lifecycle_state = 'derive_failed' AND NEW.lifecycle_state IN ('derive_pending','quarantined','tombstoned')
        OR OLD.lifecycle_state = 'derived_available' AND NEW.lifecycle_state IN ('readable','policy_blocked','quarantined','tombstoned')
        OR OLD.lifecycle_state = 'readable' AND NEW.lifecycle_state IN ('policy_blocked','retention_blocked','quarantined','tombstoned')
        OR OLD.lifecycle_state = 'policy_blocked' AND NEW.lifecycle_state IN ('derive_pending','readable','quarantined','tombstoned')
        OR OLD.lifecycle_state IN ('policy_blocked','retention_blocked','quarantined') AND NEW.lifecycle_state = 'tombstoned'
    ) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'document_versions_lifecycle_transition', MESSAGE = 'invalid document version lifecycle transition';
    END IF;
    RETURN NEW;
END;
