CREATE OR REPLACE FUNCTION enforce_document_search_index_integrity()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    version_digest text;
    version_source_id bigint;
    artifact_record derived_artifacts%ROWTYPE;
    retained_days integer;
    store_allowed boolean;
    retain_allowed boolean;
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'document_version_search_indexes_tombstone_required',
            MESSAGE = 'sensitive search indexes must be scrubbed to a retained tombstone';
    END IF;
    SELECT version.content_sha256, document.source_connection_id
    INTO version_digest, version_source_id
    FROM document_versions AS version
    JOIN documents AS document ON document.id = version.document_id
    WHERE version.id = NEW.document_version_id FOR KEY SHARE OF version, document;
    SELECT * INTO artifact_record FROM derived_artifacts
    WHERE id = NEW.derived_artifact_id FOR KEY SHARE;
    retained_days := current_rights_retention_days(
        NEW.source_connection_id, 'document_version', NEW.document_version_id::text,
        version_digest::char(64), CASE WHEN TG_OP = 'INSERT' THEN NEW.indexed_at ELSE NEW.tombstoned_at END
    );
    store_allowed := current_rights_action_allowed(
        NEW.store_derived_rights_decision_id, NEW.source_connection_id, 'document_version',
        NEW.document_version_id::text, version_digest::char(64), 'store_derived',
        CASE WHEN TG_OP = 'INSERT' THEN NEW.indexed_at ELSE NEW.tombstoned_at END
    );
    retain_allowed := current_rights_action_allowed(
        NEW.retain_rights_decision_id, NEW.source_connection_id, 'document_version',
        NEW.document_version_id::text, version_digest::char(64), 'retain',
        CASE WHEN TG_OP = 'INSERT' THEN NEW.indexed_at ELSE NEW.tombstoned_at END
    );
    IF TG_OP = 'UPDATE' THEN
        IF OLD.lifecycle_state <> 'active' OR NEW.lifecycle_state <> 'tombstoned'
           OR NEW.id IS DISTINCT FROM OLD.id OR NEW.version IS DISTINCT FROM OLD.version
           OR NEW.document_version_id IS DISTINCT FROM OLD.document_version_id
           OR NEW.source_connection_id IS DISTINCT FROM OLD.source_connection_id
           OR NEW.derived_artifact_id IS DISTINCT FROM OLD.derived_artifact_id
           OR NEW.store_derived_rights_decision_id IS DISTINCT FROM OLD.store_derived_rights_decision_id
           OR NEW.retain_rights_decision_id IS DISTINCT FROM OLD.retain_rights_decision_id
           OR NEW.normalization_profile_version IS DISTINCT FROM OLD.normalization_profile_version
           OR NEW.normalized_text_sha256 IS DISTINCT FROM OLD.normalized_text_sha256
           OR NEW.retention_until IS DISTINCT FROM OLD.retention_until
           OR NEW.indexed_at IS DISTINCT FROM OLD.indexed_at
           OR NEW.created_at IS DISTINCT FROM OLD.created_at
           OR NEW.tombstoned_at < OLD.indexed_at
           OR NEW.purge_reason NOT IN ('rights_revoked','retention_expired')
           OR NEW.purge_reason = 'rights_revoked' AND store_allowed AND retain_allowed
           OR NEW.purge_reason = 'retention_expired' AND NEW.tombstoned_at < OLD.retention_until
        THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'document_version_search_indexes_scrub_transition',
                MESSAGE = 'search index tombstone must scrub only after rights revocation or retention expiry';
        END IF;
        RETURN NEW;
    END IF;
    IF NEW.lifecycle_state <> 'active'
       OR version_source_id IS DISTINCT FROM NEW.source_connection_id
       OR artifact_record.document_version_id IS DISTINCT FROM NEW.document_version_id
       OR artifact_record.source_connection_id IS DISTINCT FROM NEW.source_connection_id
       OR artifact_record.artifact_type IS DISTINCT FROM 'plaintext'
       OR artifact_record.lifecycle_state IS DISTINCT FROM 'derived_available'
       OR artifact_record.sha256 IS DISTINCT FROM NEW.normalized_text_sha256
       OR artifact_record.store_derived_rights_decision_id IS DISTINCT FROM NEW.store_derived_rights_decision_id
       OR artifact_record.retain_rights_decision_id IS DISTINCT FROM NEW.retain_rights_decision_id
       OR NOT store_allowed
       OR retained_days IS NULL
       OR NOT retain_allowed
       OR NEW.retention_until > artifact_record.retention_until
       OR NEW.retention_until > NEW.indexed_at + retained_days * interval '24 hours'
    THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'document_version_search_indexes_exact_rights',
            MESSAGE = 'document search index requires exact plaintext and current store_derived/retain rights';
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS document_version_search_indexes_integrity ON document_version_search_indexes;
CREATE TRIGGER document_version_search_indexes_integrity
BEFORE INSERT OR UPDATE OR DELETE ON document_version_search_indexes
FOR EACH ROW EXECUTE FUNCTION enforce_document_search_index_integrity();

CREATE OR REPLACE FUNCTION enforce_document_version_embedding_integrity()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    version_digest text;
    version_source_id bigint;
    model_record ai_model_profiles%ROWTYPE;
    run_record ai_runs%ROWTYPE;
    retained_days integer;
    embed_allowed boolean;
    retain_allowed boolean;
    search_retention_until timestamptz;
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'document_version_embeddings_tombstone_required',
            MESSAGE = 'sensitive embeddings must be scrubbed to a retained tombstone';
    END IF;
    SELECT version.content_sha256, document.source_connection_id
    INTO version_digest, version_source_id
    FROM document_versions AS version
    JOIN documents AS document ON document.id = version.document_id
    WHERE version.id = NEW.document_version_id FOR KEY SHARE OF version, document;
    SELECT * INTO model_record FROM ai_model_profiles WHERE id = NEW.model_profile_id FOR KEY SHARE;
    SELECT * INTO run_record FROM ai_runs WHERE id = NEW.ai_run_id FOR KEY SHARE;
    retained_days := current_rights_retention_days(
        NEW.source_connection_id, 'document_version', NEW.document_version_id::text,
        version_digest::char(64), CASE WHEN TG_OP = 'INSERT' THEN NEW.created_at ELSE NEW.tombstoned_at END
    );
    embed_allowed := current_rights_action_allowed(
        NEW.embed_local_rights_decision_id, NEW.source_connection_id, 'document_version',
        NEW.document_version_id::text, version_digest::char(64), 'embed_local',
        CASE WHEN TG_OP = 'INSERT' THEN NEW.created_at ELSE NEW.tombstoned_at END
    );
    retain_allowed := current_rights_action_allowed(
        NEW.retain_rights_decision_id, NEW.source_connection_id, 'document_version',
        NEW.document_version_id::text, version_digest::char(64), 'retain',
        CASE WHEN TG_OP = 'INSERT' THEN NEW.created_at ELSE NEW.tombstoned_at END
    );
    SELECT max(search.retention_until) INTO search_retention_until
    FROM document_version_search_indexes AS search
    WHERE search.document_version_id = NEW.document_version_id
      AND search.source_connection_id = NEW.source_connection_id
      AND search.normalized_text_sha256 = NEW.normalized_text_sha256
      AND search.lifecycle_state = 'active'
      AND search.retention_until > CASE WHEN TG_OP = 'INSERT' THEN NEW.created_at ELSE NEW.tombstoned_at END
      AND current_rights_action_allowed(
          search.store_derived_rights_decision_id, search.source_connection_id,
          'document_version', search.document_version_id::text, NEW.normalized_text_sha256,
          'store_derived', CASE WHEN TG_OP = 'INSERT' THEN NEW.created_at ELSE NEW.tombstoned_at END
      )
      AND current_rights_action_allowed(
          search.retain_rights_decision_id, search.source_connection_id,
          'document_version', search.document_version_id::text, NEW.normalized_text_sha256,
          'retain', CASE WHEN TG_OP = 'INSERT' THEN NEW.created_at ELSE NEW.tombstoned_at END
      );
    IF TG_OP = 'UPDATE' THEN
        IF OLD.lifecycle_state <> 'active' OR NEW.lifecycle_state <> 'tombstoned'
           OR NEW.id IS DISTINCT FROM OLD.id
           OR NEW.document_version_id IS DISTINCT FROM OLD.document_version_id
           OR NEW.source_connection_id IS DISTINCT FROM OLD.source_connection_id
           OR NEW.embed_local_rights_decision_id IS DISTINCT FROM OLD.embed_local_rights_decision_id
           OR NEW.retain_rights_decision_id IS DISTINCT FROM OLD.retain_rights_decision_id
           OR NEW.model_profile_id IS DISTINCT FROM OLD.model_profile_id
           OR NEW.model_profile_version IS DISTINCT FROM OLD.model_profile_version
           OR NEW.model_version IS DISTINCT FROM OLD.model_version
           OR NEW.normalized_text_sha256 IS DISTINCT FROM OLD.normalized_text_sha256
           OR NEW.ai_run_id IS DISTINCT FROM OLD.ai_run_id
           OR NEW.retention_until IS DISTINCT FROM OLD.retention_until
           OR NEW.created_at IS DISTINCT FROM OLD.created_at
           OR NEW.tombstoned_at < OLD.created_at
           OR NEW.purge_reason NOT IN ('rights_revoked','retention_expired')
           OR NEW.purge_reason = 'rights_revoked' AND embed_allowed AND retain_allowed
           OR NEW.purge_reason = 'retention_expired' AND NEW.tombstoned_at < OLD.retention_until
        THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'document_version_embeddings_scrub_transition',
                MESSAGE = 'embedding tombstone must scrub only after rights revocation or retention expiry';
        END IF;
        RETURN NEW;
    END IF;
    IF NEW.lifecycle_state <> 'active'
       OR version_source_id IS DISTINCT FROM NEW.source_connection_id
       OR version_digest IS DISTINCT FROM NEW.normalized_text_sha256
       OR model_record.version IS DISTINCT FROM NEW.model_profile_version
       OR model_record.model_version IS DISTINCT FROM NEW.model_version
       OR model_record.task_type IS DISTINCT FROM 'embedding'
       OR model_record.embedding_dimensions IS DISTINCT FROM 1024
       OR run_record.status IS DISTINCT FROM 'succeeded'
       OR run_record.task_type IS DISTINCT FROM 'embedding'
       OR run_record.target_type IS DISTINCT FROM 'document_version'
       OR run_record.target_id IS DISTINCT FROM NEW.document_version_id
       OR run_record.model_profile_id IS DISTINCT FROM NEW.model_profile_id
       OR run_record.model_profile_version IS DISTINCT FROM NEW.model_profile_version
       OR run_record.model_version IS DISTINCT FROM NEW.model_version
       OR run_record.input_hash IS DISTINCT FROM NEW.normalized_text_sha256
       OR NOT embed_allowed
       OR retained_days IS NULL
       OR NOT retain_allowed
       OR search_retention_until IS NULL
       OR NEW.retention_until > search_retention_until
       OR NEW.retention_until > NEW.created_at + retained_days * interval '24 hours'
    THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'document_version_embeddings_exact_rights',
            MESSAGE = 'document embedding requires exact succeeded run and current embed_local/retain rights';
    END IF;
    RETURN NEW;
END;
$$;
