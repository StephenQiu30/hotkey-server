-- Event keys are stable business identifiers. Decisions and governance audits
-- are retained facts: corrections create a new fact instead of mutating one.
CREATE OR REPLACE FUNCTION enforce_event_key_immutability()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.event_key IS DISTINCT FROM OLD.event_key THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'events_event_key_immutable', MESSAGE = 'event_key is immutable';
    END IF;
    RETURN NEW;
