CREATE OR REPLACE FUNCTION enforce_monitor_intent_preview_result_completeness()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    checked_run_id bigint;
    checked_kind text;
    checked_fingerprint text;
    result_count integer;
BEGIN
    IF TG_TABLE_NAME = 'monitor_intent_preview_results' THEN
        checked_run_id := NEW.run_id;
    ELSE
        checked_run_id := NEW.id;
    END IF;
    SELECT kind,result_fingerprint INTO checked_kind,checked_fingerprint
    FROM monitor_intent_analysis_runs WHERE id = checked_run_id;
    IF checked_kind IS DISTINCT FROM 'preview' THEN
        IF TG_TABLE_NAME = 'monitor_intent_preview_results' THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'monitor_intent_preview_result_kind',
                MESSAGE = 'preview results require a preview analysis run';
        END IF;
        RETURN NULL;
    END IF;
    SELECT count(*) INTO result_count FROM monitor_intent_preview_results WHERE run_id = checked_run_id;
    IF (checked_fingerprint IS NULL AND result_count <> 0) OR (checked_fingerprint IS NOT NULL AND result_count <> 1) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'monitor_intent_preview_result_complete',
            MESSAGE = 'a terminal successful preview and its result must be committed together';
    END IF;
    RETURN NULL;
END;
$$;
DROP TRIGGER IF EXISTS monitor_intent_analysis_runs_preview_complete ON monitor_intent_analysis_runs;
CREATE CONSTRAINT TRIGGER monitor_intent_analysis_runs_preview_complete
AFTER INSERT OR UPDATE ON monitor_intent_analysis_runs
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION enforce_monitor_intent_preview_result_completeness();
DROP TRIGGER IF EXISTS monitor_intent_preview_results_complete ON monitor_intent_preview_results;
CREATE CONSTRAINT TRIGGER monitor_intent_preview_results_complete
AFTER INSERT ON monitor_intent_preview_results
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION enforce_monitor_intent_preview_result_completeness();

-- A ready CompiledProfile is the only serving source for hybrid recall. Its
-- purpose is explicit: preview profiles bind one exact preview run and draft
-- revision, while published profiles bind one immutable MonitorVersion.
-- Legacy monitor_rules/monitor_embeddings are never a fallback.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint constraint_record
        WHERE constraint_record.conrelid = 'monitor_intent_draft_revisions'::regclass
          AND constraint_record.contype = 'u'
          AND (
              SELECT array_agg(attribute.attname::text ORDER BY key.ordinality)
              FROM unnest(constraint_record.conkey) WITH ORDINALITY AS key(attnum, ordinality)
              JOIN pg_attribute attribute
                ON attribute.attrelid = constraint_record.conrelid
               AND attribute.attnum = key.attnum
          ) = ARRAY['id','monitor_id','config_version_id']::text[]
    ) THEN
        ALTER TABLE monitor_intent_draft_revisions
            ADD CONSTRAINT monitor_intent_revisions_compilation_identity_uq
            UNIQUE (id, monitor_id, config_version_id);
    END IF;
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint constraint_record
        WHERE constraint_record.conrelid = 'monitor_intent_analysis_runs'::regclass
          AND constraint_record.contype = 'u'
          AND (
              SELECT array_agg(attribute.attname::text ORDER BY key.ordinality)
              FROM unnest(constraint_record.conkey) WITH ORDINALITY AS key(attnum, ordinality)
              JOIN pg_attribute attribute
                ON attribute.attrelid = constraint_record.conrelid
               AND attribute.attnum = key.attnum
          ) = ARRAY['id','monitor_id','draft_id','draft_resource_version']::text[]
    ) THEN
        ALTER TABLE monitor_intent_analysis_runs
            ADD CONSTRAINT monitor_intent_preview_runs_compilation_identity_uq
            UNIQUE (id, monitor_id, draft_id, draft_resource_version);
    END IF;
END;
$$;

