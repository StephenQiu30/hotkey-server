        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'source_connections_bilibili_configuration_check', MESSAGE = 'Bilibili requires the official endpoint, OAuth2 credential, authorized OpenID, policy, attribution, body storage, and deletion sync';
    END IF;
	IF NEW.source_type = 'weibo' AND (NEW.endpoint <> 'https://open.weibo.com/cli/api' OR NEW.auth_type <> 'bearer' OR NEW.credential_ref IS NULL OR NEW.terms_policy_url <> 'https://open.weibo.com/wiki/%E5%BC%80%E5%8F%91%E8%80%85%E5%8D%8F%E8%AE%AE' OR COALESCE((NEW.config->>'allow_body_storage')::boolean, false) IS NOT TRUE OR COALESCE((NEW.config->>'requires_attribution')::boolean, false) IS NOT TRUE OR COALESCE((NEW.config->>'requires_deletion_sync')::boolean, false) IS NOT TRUE) THEN
		RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'source_connections_weibo_configuration_check', MESSAGE = 'Weibo requires the official CLI API endpoint, Bearer credential, developer agreement, attribution, body storage, and deletion sync';
	END IF;
    IF NEW.source_type = 'google_agent_search' AND (
        NEW.auth_type <> 'bearer' OR NEW.credential_ref IS NULL OR NEW.terms_policy_url <> 'https://cloud.google.com/terms'
        OR COALESCE(NEW.config->>'google_location', '') NOT IN ('global','us','eu')
        OR COALESCE(NEW.config->>'google_serving_config', '') !~ '^projects/[a-z][a-z0-9-]{4,28}[a-z0-9]/locations/(global|us|eu)/collections/default_collection/dataStores/[A-Za-z0-9_-]{1,63}/servingConfigs/[A-Za-z0-9_-]{1,63}$'
        OR position('/locations/' || (NEW.config->>'google_location') || '/' IN COALESCE(NEW.config->>'google_serving_config', '')) = 0
        OR NEW.endpoint <> CASE NEW.config->>'google_location'
            WHEN 'global' THEN 'https://discoveryengine.googleapis.com'
            WHEN 'us' THEN 'https://us-discoveryengine.googleapis.com'
            WHEN 'eu' THEN 'https://eu-discoveryengine.googleapis.com'
            ELSE '' END
        OR COALESCE((NEW.config->>'allow_body_storage')::boolean, false) IS NOT TRUE
        OR COALESCE((NEW.config->>'requires_attribution')::boolean, false) IS NOT TRUE
    ) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'source_connections_google_agent_search_configuration_check', MESSAGE = 'Google Agent Search requires a matching official endpoint, location, ServingConfig, Bearer credential, terms, attribution, and snippet storage';
    END IF;
    IF TG_OP = 'UPDATE'
       AND (NEW.source_type IS DISTINCT FROM OLD.source_type OR NEW.endpoint IS DISTINCT FROM OLD.endpoint OR NEW.config IS DISTINCT FROM OLD.config)
       AND NOT (
           NEW.source_type IS NOT DISTINCT FROM OLD.source_type
           AND NEW.endpoint IS NOT DISTINCT FROM OLD.endpoint
           AND (NEW.config - 'allow_body_storage') IS NOT DISTINCT FROM (OLD.config - 'allow_body_storage')
           AND COALESCE(OLD.config->>'allow_body_storage', 'false') = 'false'
           AND NEW.config->>'allow_body_storage' = 'true'
       )
       AND EXISTS (
           SELECT 1
           FROM monitor_sources AS monitor_source
           JOIN monitor_config_versions AS config_version ON config_version.id = monitor_source.config_version_id
           WHERE monitor_source.source_connection_id = OLD.id AND config_version.state IN ('published', 'superseded')
       ) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'source_connections_semantic_immutable', MESSAGE = 'published monitor configuration source semantics are immutable';
    END IF;
    RETURN NEW;
END;
$$;

