CREATE TABLE IF NOT EXISTS metric_capability_profiles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint NOT NULL DEFAULT 1,
    source_type varchar(24) NOT NULL CHECK (source_type IN ('rss','hacker_news','x','bilibili','weibo')),
    profile_version varchar(64) NOT NULL CHECK (profile_version ~ '^[a-z][a-z0-9._-]{0,63}$'),
    supports_views boolean NOT NULL DEFAULT false,
    supports_likes boolean NOT NULL DEFAULT false,
    supports_comments boolean NOT NULL DEFAULT false,
    supports_shares boolean NOT NULL DEFAULT false,
    independence_strategy varchar(24) NOT NULL CHECK (independence_strategy IN ('source_connection','author')),
    normalization_window_hours integer NOT NULL CHECK (normalization_window_hours BETWEEN 1 AND 720),
    credibility_weight numeric(4,3) NOT NULL CHECK (credibility_weight BETWEEN 0 AND 1),
    max_single_item_contribution numeric(5,2) NOT NULL CHECK (max_single_item_contribution > 0 AND max_single_item_contribution <= 100),
    status varchar(16) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','published','archived')),
    published_at timestamptz,
    archived_at timestamptz,
    created_by bigint REFERENCES users(id) ON DELETE SET NULL,
    updated_by bigint REFERENCES users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (source_type, profile_version),
    CHECK ((supports_views OR supports_likes OR supports_comments OR supports_shares)
        AND ((status = 'draft' AND published_at IS NULL AND archived_at IS NULL)
          OR (status = 'published' AND published_at IS NOT NULL AND archived_at IS NULL)
          OR (status = 'archived' AND archived_at IS NOT NULL)))
);
CREATE UNIQUE INDEX IF NOT EXISTS metric_capability_profiles_one_published_uq
    ON metric_capability_profiles(source_type) WHERE status = 'published';
