       OR NEW.created_at IS DISTINCT FROM OLD.created_at
       OR NEW.version <> OLD.version + 1 THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'document_versions_content_immutable', MESSAGE = 'document version content and provenance are immutable';
    END IF;
