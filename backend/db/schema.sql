            ERRCODE = '23514',
            CONSTRAINT = 'auth_refresh_tokens_expires_within_session_check',
            MESSAGE = 'auth refresh token expiry must not exceed session absolute expiry';
    END IF;
    RETURN NEW;
END;
$$;

