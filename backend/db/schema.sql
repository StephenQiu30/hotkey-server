CREATE OR REPLACE FUNCTION current_rights_action_is_allowed(
    selected_source_connection_id bigint,
    selected_subject_type varchar,
    selected_subject_key varchar,
    selected_input_digest char(64),
    selected_action varchar,
    decision_at timestamptz
)
RETURNS boolean
LANGUAGE sql
STABLE
AS $$
WITH terminal AS (
    SELECT decision.*
    FROM source_rights_decisions AS decision
    WHERE decision.source_connection_id = selected_source_connection_id
      AND decision.subject_type = selected_subject_type
      AND decision.subject_key = selected_subject_key
      AND decision.input_digest = selected_input_digest
      AND decision.action = selected_action
      AND decision.effective_from <= decision_at
      AND (decision.expires_at IS NULL OR decision_at < decision.expires_at)
      AND NOT EXISTS (
          SELECT 1 FROM source_rights_decisions AS superseding
          WHERE superseding.supersedes_decision_id = decision.id
            AND superseding.effective_from <= decision_at
      )
), highest AS (
    SELECT max(priority_rank) AS priority_rank FROM terminal
)
SELECT EXISTS (SELECT 1 FROM terminal, highest WHERE terminal.priority_rank = highest.priority_rank)
AND NOT EXISTS (
    SELECT 1 FROM terminal, highest
    WHERE terminal.priority_rank = highest.priority_rank AND terminal.decision <> 'allow'
)
$$;

CREATE OR REPLACE FUNCTION current_rights_retention_days(
    selected_source_connection_id bigint,
    selected_subject_type varchar,
    selected_subject_key varchar,
    selected_input_digest char(64),
    decision_at timestamptz
)
RETURNS integer
LANGUAGE sql
STABLE
AS $$
WITH terminal AS (
    SELECT decision.*
    FROM source_rights_decisions AS decision
    WHERE decision.source_connection_id = selected_source_connection_id
      AND decision.subject_type = selected_subject_type
      AND decision.subject_key = selected_subject_key
      AND decision.input_digest = selected_input_digest
      AND decision.action = 'retain'
      AND decision.effective_from <= decision_at
      AND (decision.expires_at IS NULL OR decision_at < decision.expires_at)
      AND NOT EXISTS (
          SELECT 1 FROM source_rights_decisions AS superseding
          WHERE superseding.supersedes_decision_id = decision.id
            AND superseding.effective_from <= decision_at
      )
), highest AS (
    SELECT max(priority_rank) AS priority_rank FROM terminal
)
SELECT CASE
    WHEN EXISTS (SELECT 1 FROM terminal, highest WHERE terminal.priority_rank = highest.priority_rank)
     AND NOT EXISTS (SELECT 1 FROM terminal, highest WHERE terminal.priority_rank = highest.priority_rank AND terminal.decision <> 'allow')
    THEN (SELECT min(retention_days) FROM terminal, highest WHERE terminal.priority_rank = highest.priority_rank)
END
$$;

