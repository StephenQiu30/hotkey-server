CREATE OR REPLACE FUNCTION enforce_monitor_intent_candidate_origin()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    origin_kind text;
    origin_draft_id bigint;
    origin_input_hash text;
BEGIN
    IF NEW.origin_run_id IS NULL THEN
        RETURN NEW;
    END IF;
    SELECT kind,draft_id,input_hash INTO origin_kind,origin_draft_id,origin_input_hash
    FROM monitor_intent_analysis_runs WHERE id = NEW.origin_run_id FOR KEY SHARE;
    IF origin_kind IS DISTINCT FROM 'expansion' OR origin_draft_id IS DISTINCT FROM NEW.draft_id
       OR origin_input_hash IS DISTINCT FROM NEW.input_hash THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'monitor_intent_candidates_origin_binding',
            MESSAGE = 'expansion candidate provenance must match its expansion run';
    END IF;
    RETURN NEW;
END;
$$;
