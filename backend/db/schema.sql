CREATE TABLE IF NOT EXISTS source_connections (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint NOT NULL DEFAULT 1,
    source_type varchar(24) NOT NULL CHECK (source_type IN ('rss','hacker_news','x','bing_grounding','bilibili','weibo','google_agent_search')),
    name varchar(120) NOT NULL, endpoint text NOT NULL,
    auth_type varchar(24) NOT NULL DEFAULT 'none' CHECK (auth_type IN ('none','api_key','oauth2','bearer')),
    credential_ref text CONSTRAINT source_connections_credential_ref_rule CHECK ((auth_type = 'none' AND credential_ref IS NULL) OR (auth_type <> 'none' AND (credential_ref ~ '^env:[A-Z_][A-Z0-9_]{0,127}$' OR credential_ref = 'managed:v1'))),
    config jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(config) = 'object'), enabled boolean NOT NULL DEFAULT true,
    health_status varchar(16) NOT NULL DEFAULT 'unknown' CHECK (health_status IN ('unknown','healthy','degraded','unavailable')),
    terms_policy_url text,
    created_by bigint REFERENCES users(id) ON DELETE SET NULL,
    updated_by bigint REFERENCES users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(), deleted_at timestamptz,
    body_storage_default_migrated_at timestamptz
);
CREATE UNIQUE INDEX IF NOT EXISTS source_connections_active_name_uq ON source_connections(name) WHERE deleted_at IS NULL;

