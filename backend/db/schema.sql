    WHERE enabled AND approval_status = 'approved'
      AND rule_type IN ('keyword','phrase','entity','exclude_keyword');

CREATE OR REPLACE FUNCTION enforce_monitor_config_version_immutability()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.state <> 'draft' OR NEW.config_hash IS NOT NULL OR NEW.published_at IS NOT NULL THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'monitor_config_versions_initial_draft_check', MESSAGE = 'monitor configuration versions must be created as drafts';
        END IF;
        RETURN NEW;
    END IF;

    IF TG_OP = 'DELETE' THEN
        IF EXISTS (
            SELECT 1
            FROM monitors
            WHERE draft_config_version_id = OLD.id OR published_config_version_id = OLD.id
        ) THEN
            RETURN OLD;
        END IF;
        IF OLD.state <> 'draft' THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'monitor_config_versions_immutable', MESSAGE = 'published monitor configuration versions are immutable';
        END IF;
        RETURN OLD;
    END IF;

    IF OLD.state = 'superseded' THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'monitor_config_versions_immutable', MESSAGE = 'superseded monitor configuration versions are immutable';
    END IF;
    IF OLD.state = 'published' THEN
        IF NEW.state <> 'superseded'
           OR NEW.monitor_id IS DISTINCT FROM OLD.monitor_id
           OR NEW.revision IS DISTINCT FROM OLD.revision
           OR NEW.version IS DISTINCT FROM OLD.version
           OR NEW.timezone IS DISTINCT FROM OLD.timezone
           OR NEW.languages IS DISTINCT FROM OLD.languages
           OR NEW.regions IS DISTINCT FROM OLD.regions
           OR NEW.collection_interval_seconds IS DISTINCT FROM OLD.collection_interval_seconds
           OR NEW.relevance_threshold IS DISTINCT FROM OLD.relevance_threshold
           OR NEW.event_threshold IS DISTINCT FROM OLD.event_threshold
           OR NEW.alert_min_heat IS DISTINCT FROM OLD.alert_min_heat
           OR NEW.alert_min_momentum IS DISTINCT FROM OLD.alert_min_momentum
           OR NEW.alert_min_breadth IS DISTINCT FROM OLD.alert_min_breadth
           OR NEW.alert_warning_threshold IS DISTINCT FROM OLD.alert_warning_threshold
           OR NEW.alert_critical_threshold IS DISTINCT FROM OLD.alert_critical_threshold
           OR NEW.alert_cooldown_minutes IS DISTINCT FROM OLD.alert_cooldown_minutes
           OR NEW.alert_email_enabled IS DISTINCT FROM OLD.alert_email_enabled
           OR NEW.alert_email_min_severity IS DISTINCT FROM OLD.alert_email_min_severity
           OR NEW.retention_days IS DISTINCT FROM OLD.retention_days
           OR NEW.config_hash IS DISTINCT FROM OLD.config_hash
           OR NEW.published_at IS DISTINCT FROM OLD.published_at
           OR NEW.created_by IS DISTINCT FROM OLD.created_by
           OR NEW.updated_by IS DISTINCT FROM OLD.updated_by
           OR NEW.created_at IS DISTINCT FROM OLD.created_at
           OR NEW.updated_at IS DISTINCT FROM OLD.updated_at THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'monitor_config_versions_immutable', MESSAGE = 'published monitor configuration versions are immutable';
        END IF;
        RETURN NEW;
    END IF;

    IF NEW.state = 'published' THEN
        IF NEW.config_hash IS NULL OR NEW.published_at IS NULL THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'monitor_config_versions_publish_check', MESSAGE = 'published monitor configuration requires hash and timestamp';
        END IF;
    ELSIF NEW.state <> 'draft' THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'monitor_config_versions_state_transition_check', MESSAGE = 'draft configuration must publish before superseding';
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS monitor_config_versions_immutable ON monitor_config_versions;
CREATE TRIGGER monitor_config_versions_immutable
BEFORE INSERT OR UPDATE OR DELETE ON monitor_config_versions
FOR EACH ROW EXECUTE FUNCTION enforce_monitor_config_version_immutability();

CREATE OR REPLACE FUNCTION enforce_monitor_config_child_immutability()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    current_config_version_id bigint;
    current_state varchar(16);
    prior_state varchar(16);
BEGIN
    IF TG_OP = 'DELETE' THEN
        current_config_version_id := OLD.config_version_id;
    ELSE
        current_config_version_id := NEW.config_version_id;
    END IF;
    SELECT state INTO current_state FROM monitor_config_versions WHERE id = current_config_version_id;
    IF current_state IS DISTINCT FROM 'draft' THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = TG_TABLE_NAME || '_immutable', MESSAGE = 'published monitor configuration children are immutable';
    END IF;
    IF TG_OP = 'UPDATE' AND NEW.config_version_id IS DISTINCT FROM OLD.config_version_id THEN
        SELECT state INTO prior_state FROM monitor_config_versions WHERE id = OLD.config_version_id;
        IF prior_state IS DISTINCT FROM 'draft' THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = TG_TABLE_NAME || '_immutable', MESSAGE = 'published monitor configuration children are immutable';
        END IF;
    END IF;
    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END;
$$;

DROP TRIGGER IF EXISTS monitor_rules_immutable ON monitor_rules;
CREATE TRIGGER monitor_rules_immutable
BEFORE INSERT OR UPDATE OR DELETE ON monitor_rules
FOR EACH ROW EXECUTE FUNCTION enforce_monitor_config_child_immutability();

DROP TRIGGER IF EXISTS monitor_sources_immutable ON monitor_sources;
CREATE TRIGGER monitor_sources_immutable
BEFORE INSERT OR UPDATE OR DELETE ON monitor_sources
FOR EACH ROW EXECUTE FUNCTION enforce_monitor_config_child_immutability();

CREATE OR REPLACE FUNCTION enforce_monitor_config_pointers()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    draft_state varchar(16);
    published_state varchar(16);
BEGIN
    IF NEW.draft_config_version_id IS NOT NULL THEN
        SELECT state INTO draft_state FROM monitor_config_versions WHERE id = NEW.draft_config_version_id AND monitor_id = NEW.id;
        IF draft_state IS DISTINCT FROM 'draft' THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'monitors_draft_config_version_owner_check', MESSAGE = 'draft configuration does not belong to monitor or is not a draft';
        END IF;
    END IF;
    IF NEW.published_config_version_id IS NOT NULL THEN
        SELECT state INTO published_state FROM monitor_config_versions WHERE id = NEW.published_config_version_id AND monitor_id = NEW.id;
        IF published_state IS DISTINCT FROM 'published' THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'monitors_published_config_version_owner_check', MESSAGE = 'published configuration does not belong to monitor or is not published';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS monitors_config_pointer_owner ON monitors;
CREATE TRIGGER monitors_config_pointer_owner
BEFORE INSERT OR UPDATE OF draft_config_version_id, published_config_version_id ON monitors
FOR EACH ROW EXECUTE FUNCTION enforce_monitor_config_pointers();

CREATE OR REPLACE FUNCTION validate_source_connection_configuration()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    config_key text;
BEGIN
    IF jsonb_typeof(NEW.config) <> 'object' THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'source_connections_config_object_check', MESSAGE = 'source config must be an object';
    END IF;
    FOR config_key IN SELECT jsonb_object_keys(NEW.config)
    LOOP
        IF config_key NOT IN ('allow_body_storage', 'requires_attribution', 'requires_deletion_sync', 'content_retention_days', 'metrics_retention_days', 'allowed_languages', 'allowed_regions', 'rate_limit_per_minute', 'request_timeout_seconds', 'max_pages_per_run', 'grounding_data_boundary_approved', 'bilibili_open_id', 'google_location', 'google_serving_config', 'hacker_news_mode') THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'source_connections_config_whitelist_check', MESSAGE = 'source config contains an unsupported key';
        END IF;
    END LOOP;
    IF (NEW.config ? 'allow_body_storage' AND jsonb_typeof(NEW.config->'allow_body_storage') <> 'boolean')
       OR (NEW.config ? 'requires_attribution' AND jsonb_typeof(NEW.config->'requires_attribution') <> 'boolean')
       OR (NEW.config ? 'requires_deletion_sync' AND jsonb_typeof(NEW.config->'requires_deletion_sync') <> 'boolean')
       OR (NEW.config ? 'grounding_data_boundary_approved' AND jsonb_typeof(NEW.config->'grounding_data_boundary_approved') <> 'boolean') THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'source_connections_config_boolean_check', MESSAGE = 'source config boolean value is invalid';
    END IF;
    IF (NEW.config ? 'content_retention_days' AND (jsonb_typeof(NEW.config->'content_retention_days') <> 'number' OR (NEW.config->>'content_retention_days')::numeric <> trunc((NEW.config->>'content_retention_days')::numeric) OR (NEW.config->>'content_retention_days')::integer NOT BETWEEN 1 AND 3650))
       OR (NEW.config ? 'metrics_retention_days' AND (jsonb_typeof(NEW.config->'metrics_retention_days') <> 'number' OR (NEW.config->>'metrics_retention_days')::numeric <> trunc((NEW.config->>'metrics_retention_days')::numeric) OR (NEW.config->>'metrics_retention_days')::integer NOT BETWEEN 1 AND 3650))
       OR (NEW.config ? 'rate_limit_per_minute' AND (jsonb_typeof(NEW.config->'rate_limit_per_minute') <> 'number' OR (NEW.config->>'rate_limit_per_minute')::numeric <> trunc((NEW.config->>'rate_limit_per_minute')::numeric) OR (NEW.config->>'rate_limit_per_minute')::integer NOT BETWEEN 1 AND 600))
       OR (NEW.config ? 'request_timeout_seconds' AND (jsonb_typeof(NEW.config->'request_timeout_seconds') <> 'number' OR (NEW.config->>'request_timeout_seconds')::numeric <> trunc((NEW.config->>'request_timeout_seconds')::numeric) OR (NEW.config->>'request_timeout_seconds')::integer NOT BETWEEN 1 AND 120))
