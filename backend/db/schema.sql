          AND title_trigrams IS NULL AND body_trigrams IS NULL
          AND entity_keys IS NULL AND action_keys IS NULL AND location_keys IS NULL
          AND region_keys IS NULL
          AND tombstoned_at IS NOT NULL AND purge_reason IS NOT NULL
    ),
    CHECK (title_trigrams IS NULL OR cardinality(title_trigrams) <= 20000),
    CHECK (body_trigrams IS NULL OR cardinality(body_trigrams) <= 200000),
    CHECK (entity_keys IS NULL OR cardinality(entity_keys) <= 512),
    CHECK (action_keys IS NULL OR cardinality(action_keys) <= 512),
    CHECK (location_keys IS NULL OR cardinality(location_keys) <= 512),
    CHECK (region_keys IS NULL OR cardinality(region_keys) <= 512)
