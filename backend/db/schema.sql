AS $$
DECLARE
    policy_record source_rights_policies%ROWTYPE;
    superseded_record source_rights_decisions%ROWTYPE;
BEGIN
    SELECT * INTO policy_record FROM source_rights_policies WHERE id = NEW.policy_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'source_rights_decisions_policy_binding', MESSAGE = 'rights decision policy is missing';
    END IF;
    IF NEW.policy_revision IS DISTINCT FROM policy_record.policy_revision
       OR NEW.policy_scope_type IS DISTINCT FROM policy_record.scope_type
       OR NEW.policy_scope_subject IS DISTINCT FROM policy_record.scope_subject
       OR NEW.priority_rank IS DISTINCT FROM policy_record.priority
       OR NEW.basis_summary IS DISTINCT FROM policy_record.basis_summary
       OR NEW.terms_url IS DISTINCT FROM policy_record.terms_url
       OR NEW.license_uri IS DISTINCT FROM policy_record.license_uri THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'source_rights_decisions_policy_snapshot', MESSAGE = 'rights decision policy snapshot does not match immutable policy';
    END IF;
    IF NEW.decision = 'allow' AND policy_record.approved_by_user_id IS NULL THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'source_rights_decisions_policy_approval',
            MESSAGE = 'allow decision requires an approved immutable policy';
    END IF;
    IF policy_record.scope_type = 'organization_default' THEN
        IF policy_record.source_connection_id IS NOT NULL THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'source_rights_decisions_policy_source', MESSAGE = 'organization policy source is invalid';
        END IF;
    ELSIF policy_record.source_connection_id IS DISTINCT FROM NEW.source_connection_id THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'source_rights_decisions_policy_source', MESSAGE = 'rights decision source does not match policy source';
    END IF;
    IF NEW.effective_from < policy_record.effective_at
       OR (policy_record.expires_at IS NOT NULL AND (NEW.expires_at IS NULL OR NEW.expires_at > policy_record.expires_at)) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'source_rights_decisions_policy_lifetime', MESSAGE = 'rights decision lifetime exceeds policy lifetime';
    END IF;
    IF NEW.supersedes_decision_id IS NOT NULL THEN
        SELECT * INTO superseded_record FROM source_rights_decisions WHERE id = NEW.supersedes_decision_id;
        IF NOT FOUND
           OR superseded_record.source_connection_id IS DISTINCT FROM NEW.source_connection_id
           OR superseded_record.subject_type IS DISTINCT FROM NEW.subject_type
           OR superseded_record.subject_key IS DISTINCT FROM NEW.subject_key
           OR superseded_record.input_digest IS DISTINCT FROM NEW.input_digest
           OR superseded_record.action IS DISTINCT FROM NEW.action THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'source_rights_decisions_supersession', MESSAGE = 'rights decision supersession identity is invalid';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
