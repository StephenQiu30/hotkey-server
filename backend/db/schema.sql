-- Keep provider constraints convergent when this complete schema is executed
-- again after adding a provider. CREATE TABLE IF NOT EXISTS does not update
-- constraints on an existing table, so replace only the provider-related
-- checks and leave profile data and unrelated checks untouched.
ALTER TABLE ai_model_profiles DROP CONSTRAINT IF EXISTS ai_model_profiles_provider_check;
DO $$
DECLARE
    constraint_row record;
BEGIN
    FOR constraint_row IN
        SELECT constraint_definition.conname
        FROM pg_constraint AS constraint_definition
        WHERE constraint_definition.conrelid = 'ai_model_profiles'::regclass
          AND constraint_definition.contype = 'c'
          AND (
              (
                  pg_get_constraintdef(constraint_definition.oid) ILIKE '%credential_ref%'
                  AND pg_get_constraintdef(constraint_definition.oid) ILIKE '%provider%'
              )
              OR (
                  pg_get_constraintdef(constraint_definition.oid) ILIKE '%provider%'
                  AND pg_get_constraintdef(constraint_definition.oid) ILIKE '%task_type%'
                  AND pg_get_constraintdef(constraint_definition.oid) NOT ILIKE '%embedding_dimensions%'
              )
              OR (
                  pg_get_constraintdef(constraint_definition.oid) ILIKE '%provider%'
                  AND pg_get_constraintdef(constraint_definition.oid) ILIKE '%model_version%'
              )
          )
    LOOP
        EXECUTE format(
            'ALTER TABLE ai_model_profiles DROP CONSTRAINT %I',
            constraint_row.conname
        );
    END LOOP;
END $$;
