    query_signature char(64), source_options jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (source_options = '{}'::jsonb), priority smallint NOT NULL DEFAULT 100,
    enabled boolean NOT NULL DEFAULT true, created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (config_version_id, source_connection_id), UNIQUE (id, config_version_id)
);
CREATE INDEX IF NOT EXISTS monitor_sources_relevance_active_source_idx
    ON monitor_sources(source_connection_id, priority, config_version_id)
    WHERE enabled;
CREATE INDEX IF NOT EXISTS monitor_rules_relevance_approved_lexical_idx
    ON monitor_rules(lower(value), config_version_id, origin, weight DESC, id)
    WHERE enabled AND approval_status = 'approved'
      AND rule_type IN ('keyword','phrase','entity','exclude_keyword');

CREATE OR REPLACE FUNCTION enforce_monitor_config_version_immutability()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.state <> 'draft' OR NEW.config_hash IS NOT NULL OR NEW.published_at IS NOT NULL THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'monitor_config_versions_initial_draft_check', MESSAGE = 'monitor configuration versions must be created as drafts';
        END IF;
        RETURN NEW;
    END IF;

    IF TG_OP = 'DELETE' THEN
        IF EXISTS (
            SELECT 1
            FROM monitors
            WHERE draft_config_version_id = OLD.id OR published_config_version_id = OLD.id
        ) THEN
            RETURN OLD;
        END IF;
        IF OLD.state <> 'draft' THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'monitor_config_versions_immutable', MESSAGE = 'published monitor configuration versions are immutable';
        END IF;
        RETURN OLD;
    END IF;

    IF OLD.state = 'superseded' THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'monitor_config_versions_immutable', MESSAGE = 'superseded monitor configuration versions are immutable';
    END IF;
    IF OLD.state = 'published' THEN
        IF NEW.state <> 'superseded'
           OR NEW.monitor_id IS DISTINCT FROM OLD.monitor_id
           OR NEW.revision IS DISTINCT FROM OLD.revision
           OR NEW.version IS DISTINCT FROM OLD.version
           OR NEW.timezone IS DISTINCT FROM OLD.timezone
           OR NEW.languages IS DISTINCT FROM OLD.languages
           OR NEW.regions IS DISTINCT FROM OLD.regions
           OR NEW.collection_interval_seconds IS DISTINCT FROM OLD.collection_interval_seconds
           OR NEW.relevance_threshold IS DISTINCT FROM OLD.relevance_threshold
           OR NEW.event_threshold IS DISTINCT FROM OLD.event_threshold
           OR NEW.alert_min_heat IS DISTINCT FROM OLD.alert_min_heat
           OR NEW.alert_min_momentum IS DISTINCT FROM OLD.alert_min_momentum
           OR NEW.alert_min_breadth IS DISTINCT FROM OLD.alert_min_breadth
           OR NEW.alert_warning_threshold IS DISTINCT FROM OLD.alert_warning_threshold
           OR NEW.alert_critical_threshold IS DISTINCT FROM OLD.alert_critical_threshold
           OR NEW.alert_cooldown_minutes IS DISTINCT FROM OLD.alert_cooldown_minutes
           OR NEW.alert_email_enabled IS DISTINCT FROM OLD.alert_email_enabled
           OR NEW.alert_email_min_severity IS DISTINCT FROM OLD.alert_email_min_severity
           OR NEW.retention_days IS DISTINCT FROM OLD.retention_days
           OR NEW.config_hash IS DISTINCT FROM OLD.config_hash
           OR NEW.published_at IS DISTINCT FROM OLD.published_at
           OR NEW.created_by IS DISTINCT FROM OLD.created_by
           OR NEW.updated_by IS DISTINCT FROM OLD.updated_by
           OR NEW.created_at IS DISTINCT FROM OLD.created_at
           OR NEW.updated_at IS DISTINCT FROM OLD.updated_at THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'monitor_config_versions_immutable', MESSAGE = 'published monitor configuration versions are immutable';
        END IF;
        RETURN NEW;
    END IF;

    IF NEW.state = 'published' THEN
        IF NEW.config_hash IS NULL OR NEW.published_at IS NULL THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'monitor_config_versions_publish_check', MESSAGE = 'published monitor configuration requires hash and timestamp';
        END IF;
    ELSIF NEW.state <> 'draft' THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'monitor_config_versions_state_transition_check', MESSAGE = 'draft configuration must publish before superseding';
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS monitor_config_versions_immutable ON monitor_config_versions;
CREATE TRIGGER monitor_config_versions_immutable
BEFORE INSERT OR UPDATE OR DELETE ON monitor_config_versions
FOR EACH ROW EXECUTE FUNCTION enforce_monitor_config_version_immutability();

CREATE OR REPLACE FUNCTION enforce_monitor_config_child_immutability()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    current_config_version_id bigint;
    current_state varchar(16);
    prior_state varchar(16);
BEGIN
    IF TG_OP = 'DELETE' THEN
        current_config_version_id := OLD.config_version_id;
    ELSE
        current_config_version_id := NEW.config_version_id;
    END IF;
    SELECT state INTO current_state FROM monitor_config_versions WHERE id = current_config_version_id;
    IF current_state IS DISTINCT FROM 'draft' THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = TG_TABLE_NAME || '_immutable', MESSAGE = 'published monitor configuration children are immutable';
    END IF;
    IF TG_OP = 'UPDATE' AND NEW.config_version_id IS DISTINCT FROM OLD.config_version_id THEN
        SELECT state INTO prior_state FROM monitor_config_versions WHERE id = OLD.config_version_id;
        IF prior_state IS DISTINCT FROM 'draft' THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = TG_TABLE_NAME || '_immutable', MESSAGE = 'published monitor configuration children are immutable';
        END IF;
    END IF;
    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END;
$$;

DROP TRIGGER IF EXISTS monitor_rules_immutable ON monitor_rules;
CREATE TRIGGER monitor_rules_immutable
BEFORE INSERT OR UPDATE OR DELETE ON monitor_rules
FOR EACH ROW EXECUTE FUNCTION enforce_monitor_config_child_immutability();

DROP TRIGGER IF EXISTS monitor_sources_immutable ON monitor_sources;
CREATE TRIGGER monitor_sources_immutable
BEFORE INSERT OR UPDATE OR DELETE ON monitor_sources
FOR EACH ROW EXECUTE FUNCTION enforce_monitor_config_child_immutability();

CREATE OR REPLACE FUNCTION enforce_monitor_config_pointers()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    draft_state varchar(16);
    published_state varchar(16);
BEGIN
    IF NEW.draft_config_version_id IS NOT NULL THEN
        SELECT state INTO draft_state FROM monitor_config_versions WHERE id = NEW.draft_config_version_id AND monitor_id = NEW.id;
        IF draft_state IS DISTINCT FROM 'draft' THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'monitors_draft_config_version_owner_check', MESSAGE = 'draft configuration does not belong to monitor or is not a draft';
        END IF;
    END IF;
    IF NEW.published_config_version_id IS NOT NULL THEN
        SELECT state INTO published_state FROM monitor_config_versions WHERE id = NEW.published_config_version_id AND monitor_id = NEW.id;
        IF published_state IS DISTINCT FROM 'published' THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'monitors_published_config_version_owner_check', MESSAGE = 'published configuration does not belong to monitor or is not published';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS monitors_config_pointer_owner ON monitors;
CREATE TRIGGER monitors_config_pointer_owner
BEFORE INSERT OR UPDATE OF draft_config_version_id, published_config_version_id ON monitors
FOR EACH ROW EXECUTE FUNCTION enforce_monitor_config_pointers();

CREATE OR REPLACE FUNCTION validate_source_connection_configuration()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    config_key text;
BEGIN
    IF jsonb_typeof(NEW.config) <> 'object' THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'source_connections_config_object_check', MESSAGE = 'source config must be an object';
    END IF;
    FOR config_key IN SELECT jsonb_object_keys(NEW.config)
    LOOP
        IF config_key NOT IN ('allow_body_storage', 'requires_attribution', 'requires_deletion_sync', 'content_retention_days', 'metrics_retention_days', 'allowed_languages', 'allowed_regions', 'rate_limit_per_minute', 'request_timeout_seconds', 'max_pages_per_run', 'grounding_data_boundary_approved', 'bilibili_open_id', 'google_location', 'google_serving_config') THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'source_connections_config_whitelist_check', MESSAGE = 'source config contains an unsupported key';
        END IF;
    END LOOP;
    IF (NEW.config ? 'allow_body_storage' AND jsonb_typeof(NEW.config->'allow_body_storage') <> 'boolean')
       OR (NEW.config ? 'requires_attribution' AND jsonb_typeof(NEW.config->'requires_attribution') <> 'boolean')
       OR (NEW.config ? 'requires_deletion_sync' AND jsonb_typeof(NEW.config->'requires_deletion_sync') <> 'boolean')
       OR (NEW.config ? 'grounding_data_boundary_approved' AND jsonb_typeof(NEW.config->'grounding_data_boundary_approved') <> 'boolean') THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'source_connections_config_boolean_check', MESSAGE = 'source config boolean value is invalid';
    END IF;
    IF (NEW.config ? 'content_retention_days' AND (jsonb_typeof(NEW.config->'content_retention_days') <> 'number' OR (NEW.config->>'content_retention_days')::numeric <> trunc((NEW.config->>'content_retention_days')::numeric) OR (NEW.config->>'content_retention_days')::integer NOT BETWEEN 1 AND 3650))
       OR (NEW.config ? 'metrics_retention_days' AND (jsonb_typeof(NEW.config->'metrics_retention_days') <> 'number' OR (NEW.config->>'metrics_retention_days')::numeric <> trunc((NEW.config->>'metrics_retention_days')::numeric) OR (NEW.config->>'metrics_retention_days')::integer NOT BETWEEN 1 AND 3650))
       OR (NEW.config ? 'rate_limit_per_minute' AND (jsonb_typeof(NEW.config->'rate_limit_per_minute') <> 'number' OR (NEW.config->>'rate_limit_per_minute')::numeric <> trunc((NEW.config->>'rate_limit_per_minute')::numeric) OR (NEW.config->>'rate_limit_per_minute')::integer NOT BETWEEN 1 AND 600))
       OR (NEW.config ? 'request_timeout_seconds' AND (jsonb_typeof(NEW.config->'request_timeout_seconds') <> 'number' OR (NEW.config->>'request_timeout_seconds')::numeric <> trunc((NEW.config->>'request_timeout_seconds')::numeric) OR (NEW.config->>'request_timeout_seconds')::integer NOT BETWEEN 1 AND 120))
       OR (NEW.config ? 'max_pages_per_run' AND (jsonb_typeof(NEW.config->'max_pages_per_run') <> 'number' OR (NEW.config->>'max_pages_per_run')::numeric <> trunc((NEW.config->>'max_pages_per_run')::numeric) OR (NEW.config->>'max_pages_per_run')::integer NOT BETWEEN 1 AND 20)) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'source_connections_config_integer_check', MESSAGE = 'source config integer value is invalid';
    END IF;
    IF (NEW.config ? 'allowed_languages' AND (jsonb_typeof(NEW.config->'allowed_languages') <> 'array' OR jsonb_array_length(NEW.config->'allowed_languages') > 8 OR EXISTS (SELECT 1 FROM jsonb_array_elements(NEW.config->'allowed_languages') AS value WHERE jsonb_typeof(value) <> 'string')))
       OR (NEW.config ? 'allowed_regions' AND (jsonb_typeof(NEW.config->'allowed_regions') <> 'array' OR jsonb_array_length(NEW.config->'allowed_regions') > 8 OR EXISTS (SELECT 1 FROM jsonb_array_elements(NEW.config->'allowed_regions') AS value WHERE jsonb_typeof(value) <> 'string'))) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'source_connections_config_array_check', MESSAGE = 'source config array value is invalid';
    END IF;
    IF NEW.config ? 'bilibili_open_id' AND COALESCE(NEW.config->>'bilibili_open_id', '') <> '' AND (jsonb_typeof(NEW.config->'bilibili_open_id') <> 'string' OR NEW.config->>'bilibili_open_id' !~ '^[A-Za-z0-9_-]{1,128}$') THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'source_connections_bilibili_open_id_check', MESSAGE = 'Bilibili OpenID is invalid';
    END IF;
    IF (NEW.config ? 'google_location' AND jsonb_typeof(NEW.config->'google_location') <> 'string')
       OR (NEW.config ? 'google_serving_config' AND jsonb_typeof(NEW.config->'google_serving_config') <> 'string') THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'source_connections_google_config_string_check', MESSAGE = 'Google Agent Search config string is invalid';
    END IF;
    IF NEW.source_type = 'hacker_news' AND NEW.endpoint <> 'https://hacker-news.firebaseio.com/v0' THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'source_connections_hacker_news_endpoint_check', MESSAGE = 'hacker news endpoint must be the official endpoint';
    END IF;
    IF NEW.source_type = 'x' AND (NEW.endpoint <> 'https://api.x.com/2/tweets/search/recent' OR NEW.auth_type <> 'bearer' OR NEW.credential_ref IS NULL) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'source_connections_x_configuration_check', MESSAGE = 'X requires the official recent search endpoint and Bearer env credential';
    END IF;
    IF NEW.source_type = 'bing_grounding' AND (NEW.endpoint !~ '^https://[A-Za-z0-9-]+\.services\.ai\.azure\.com/api/projects/[A-Za-z0-9][A-Za-z0-9._-]{0,127}/toolboxes/[A-Za-z0-9][A-Za-z0-9._-]{0,127}/versions/[A-Za-z0-9][A-Za-z0-9._-]{0,127}/mcp\?api-version=v1$' OR NEW.auth_type <> 'bearer' OR NEW.credential_ref IS NULL OR NEW.terms_policy_url IS NULL OR NEW.terms_policy_url !~ '^https://' OR COALESCE((NEW.config->>'allow_body_storage')::boolean, false) IS NOT TRUE OR COALESCE((NEW.config->>'requires_attribution')::boolean, false) IS NOT TRUE OR COALESCE((NEW.config->>'max_pages_per_run')::integer, 0) <> 1) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'source_connections_bing_grounding_configuration_check', MESSAGE = 'Bing Grounding requires a versioned Foundry Toolbox MCP endpoint, Bearer env credential, attribution, body storage, and one page';
    END IF;
    IF NEW.source_type = 'bilibili' AND (NEW.endpoint <> 'https://member.bilibili.com/arcopen/fn' OR NEW.auth_type <> 'oauth2' OR NEW.credential_ref IS NULL OR NEW.terms_policy_url <> 'https://openhome.bilibili.com/agreement/privacy-policy' OR COALESCE(NEW.config->>'bilibili_open_id', '') !~ '^[A-Za-z0-9_-]{1,128}$' OR COALESCE((NEW.config->>'allow_body_storage')::boolean, false) IS NOT TRUE OR COALESCE((NEW.config->>'requires_attribution')::boolean, false) IS NOT TRUE OR COALESCE((NEW.config->>'requires_deletion_sync')::boolean, false) IS NOT TRUE) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'source_connections_bilibili_configuration_check', MESSAGE = 'Bilibili requires the official endpoint, OAuth2 env credential, authorized OpenID, policy, attribution, body storage, and deletion sync';
    END IF;
	IF NEW.source_type = 'weibo' AND (NEW.endpoint <> 'https://open.weibo.com/cli/api' OR NEW.auth_type <> 'bearer' OR NEW.credential_ref IS NULL OR NEW.terms_policy_url <> 'https://open.weibo.com/wiki/%E5%BC%80%E5%8F%91%E8%80%85%E5%8D%8F%E8%AE%AE' OR COALESCE((NEW.config->>'allow_body_storage')::boolean, false) IS NOT TRUE OR COALESCE((NEW.config->>'requires_attribution')::boolean, false) IS NOT TRUE OR COALESCE((NEW.config->>'requires_deletion_sync')::boolean, false) IS NOT TRUE) THEN
		RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'source_connections_weibo_configuration_check', MESSAGE = 'Weibo requires the official CLI API endpoint, Bearer env credential, developer agreement, attribution, body storage, and deletion sync';
	END IF;
    IF NEW.source_type = 'google_agent_search' AND (
        NEW.auth_type <> 'bearer' OR NEW.credential_ref IS NULL OR NEW.terms_policy_url <> 'https://cloud.google.com/terms'
        OR COALESCE(NEW.config->>'google_location', '') NOT IN ('global','us','eu')
        OR COALESCE(NEW.config->>'google_serving_config', '') !~ '^projects/[a-z][a-z0-9-]{4,28}[a-z0-9]/locations/(global|us|eu)/collections/default_collection/dataStores/[A-Za-z0-9_-]{1,63}/servingConfigs/[A-Za-z0-9_-]{1,63}$'
        OR position('/locations/' || (NEW.config->>'google_location') || '/' IN COALESCE(NEW.config->>'google_serving_config', '')) = 0
        OR NEW.endpoint <> CASE NEW.config->>'google_location'
            WHEN 'global' THEN 'https://discoveryengine.googleapis.com'
            WHEN 'us' THEN 'https://us-discoveryengine.googleapis.com'
            WHEN 'eu' THEN 'https://eu-discoveryengine.googleapis.com'
            ELSE '' END
        OR COALESCE((NEW.config->>'allow_body_storage')::boolean, false) IS NOT TRUE
        OR COALESCE((NEW.config->>'requires_attribution')::boolean, false) IS NOT TRUE
    ) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'source_connections_google_agent_search_configuration_check', MESSAGE = 'Google Agent Search requires a matching official endpoint, location, ServingConfig, Bearer env credential, terms, attribution, and snippet storage';
    END IF;
    IF TG_OP = 'UPDATE'
       AND (NEW.source_type IS DISTINCT FROM OLD.source_type OR NEW.endpoint IS DISTINCT FROM OLD.endpoint OR NEW.config IS DISTINCT FROM OLD.config)
       AND NOT (
           NEW.source_type IS NOT DISTINCT FROM OLD.source_type
           AND NEW.endpoint IS NOT DISTINCT FROM OLD.endpoint
           AND (NEW.config - 'allow_body_storage') IS NOT DISTINCT FROM (OLD.config - 'allow_body_storage')
           AND COALESCE(OLD.config->>'allow_body_storage', 'false') = 'false'
           AND NEW.config->>'allow_body_storage' = 'true'
       )
       AND EXISTS (
           SELECT 1
           FROM monitor_sources AS monitor_source
           JOIN monitor_config_versions AS config_version ON config_version.id = monitor_source.config_version_id
           WHERE monitor_source.source_connection_id = OLD.id AND config_version.state IN ('published', 'superseded')
       ) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'source_connections_semantic_immutable', MESSAGE = 'published monitor configuration source semantics are immutable';
    END IF;
    RETURN NEW;
END;
$$;

