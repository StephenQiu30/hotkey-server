CREATE OR REPLACE FUNCTION enforce_monitor_intent_draft_lifecycle()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    config_state text;
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'monitor_intent_drafts_retained',
            MESSAGE = 'monitor intent drafts are retained';
    END IF;
    IF TG_OP = 'UPDATE' AND (
        NEW.id IS DISTINCT FROM OLD.id OR NEW.monitor_id IS DISTINCT FROM OLD.monitor_id
        OR NEW.config_version_id IS DISTINCT FROM OLD.config_version_id
        OR NEW.created_at IS DISTINCT FROM OLD.created_at
        OR NEW.resource_version <> OLD.resource_version + 1
    ) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'monitor_intent_drafts_identity_immutable',
            MESSAGE = 'monitor intent draft identity is immutable and its resource version advances by one';
    END IF;
    SELECT state INTO config_state FROM monitor_config_versions
    WHERE id = NEW.config_version_id AND monitor_id = NEW.monitor_id FOR KEY SHARE;
    IF config_state IS DISTINCT FROM 'draft' THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'monitor_intent_drafts_config_mutable',
            MESSAGE = 'monitor intent may only change while its configuration is a draft';
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS monitor_intent_drafts_lifecycle ON monitor_intent_drafts;
CREATE TRIGGER monitor_intent_drafts_lifecycle
BEFORE INSERT OR UPDATE OR DELETE ON monitor_intent_drafts
FOR EACH ROW EXECUTE FUNCTION enforce_monitor_intent_draft_lifecycle();

