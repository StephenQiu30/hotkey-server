CREATE OR REPLACE FUNCTION enforce_metric_capability_profile_immutability()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'metric_capability_profiles_append_only_check', MESSAGE = 'metric capability profiles cannot be deleted';
    END IF;
    IF OLD.status = 'archived' THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'metric_capability_profiles_archived_immutable_check', MESSAGE = 'archived metric capability profiles cannot be changed';
    END IF;
    IF OLD.status = 'published' AND (
        NEW.source_type IS DISTINCT FROM OLD.source_type
        OR NEW.profile_version IS DISTINCT FROM OLD.profile_version
        OR NEW.supports_views IS DISTINCT FROM OLD.supports_views
        OR NEW.supports_likes IS DISTINCT FROM OLD.supports_likes
        OR NEW.supports_comments IS DISTINCT FROM OLD.supports_comments
        OR NEW.supports_shares IS DISTINCT FROM OLD.supports_shares
        OR NEW.independence_strategy IS DISTINCT FROM OLD.independence_strategy
        OR NEW.normalization_window_hours IS DISTINCT FROM OLD.normalization_window_hours
        OR NEW.credibility_weight IS DISTINCT FROM OLD.credibility_weight
        OR NEW.max_single_item_contribution IS DISTINCT FROM OLD.max_single_item_contribution
        OR NEW.published_at IS DISTINCT FROM OLD.published_at
    ) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'metric_capability_profiles_published_immutable_check', MESSAGE = 'published metric capability configuration is immutable';
    END IF;
    IF OLD.status = 'published' AND NEW.status NOT IN ('published','archived') THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'metric_capability_profiles_transition_check', MESSAGE = 'published metric capability profile can only be archived';
    END IF;
    IF OLD.status = 'draft' AND NEW.status NOT IN ('draft','published','archived') THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'metric_capability_profiles_transition_check', MESSAGE = 'invalid metric capability profile transition';
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS metric_capability_profiles_immutable ON metric_capability_profiles;
CREATE TRIGGER metric_capability_profiles_immutable
BEFORE UPDATE OR DELETE ON metric_capability_profiles
FOR EACH ROW EXECUTE FUNCTION enforce_metric_capability_profile_immutability();

CREATE TABLE IF NOT EXISTS monitors (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint NOT NULL DEFAULT 1,
    name varchar(120) NOT NULL, description text NOT NULL DEFAULT '',
    status varchar(16) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','active','paused','archived')),
    draft_config_version_id bigint, published_config_version_id bigint,
    created_by bigint REFERENCES users(id) ON DELETE SET NULL, updated_by bigint REFERENCES users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(), deleted_at timestamptz
);
CREATE UNIQUE INDEX IF NOT EXISTS monitors_active_name_uq ON monitors(lower(name)) WHERE deleted_at IS NULL AND status <> 'archived';

CREATE TABLE IF NOT EXISTS monitor_config_versions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint NOT NULL DEFAULT 1,
    monitor_id bigint NOT NULL REFERENCES monitors(id) ON DELETE RESTRICT,
    revision bigint NOT NULL CHECK (revision > 0),
    state varchar(16) NOT NULL DEFAULT 'draft' CHECK (state IN ('draft','published','superseded')),
    timezone varchar(64) NOT NULL DEFAULT 'UTC', languages text[] NOT NULL DEFAULT '{}', regions text[] NOT NULL DEFAULT '{}',
    collection_interval_seconds integer NOT NULL DEFAULT 300 CHECK (collection_interval_seconds BETWEEN 300 AND 86400 AND mod(collection_interval_seconds, 60) = 0),
    relevance_threshold numeric(5,2) NOT NULL DEFAULT 60 CHECK (relevance_threshold BETWEEN 60 AND 100),
    event_threshold numeric(5,2) NOT NULL DEFAULT 0 CHECK (event_threshold BETWEEN 0 AND 100),
    alert_min_heat numeric(5,2) NOT NULL DEFAULT 70 CHECK (alert_min_heat BETWEEN 0 AND 100),
    alert_min_momentum numeric(5,2) NOT NULL DEFAULT 55 CHECK (alert_min_momentum BETWEEN 0 AND 100),
    alert_min_breadth numeric(5,2) NOT NULL DEFAULT 25 CHECK (alert_min_breadth BETWEEN 0 AND 100),
    alert_warning_threshold numeric(5,2) NOT NULL DEFAULT 75 CHECK (alert_warning_threshold BETWEEN 0 AND 100),
    alert_critical_threshold numeric(5,2) NOT NULL DEFAULT 90 CHECK (alert_critical_threshold BETWEEN 0 AND 100 AND alert_critical_threshold >= alert_warning_threshold),
    alert_cooldown_minutes integer NOT NULL DEFAULT 60 CHECK (alert_cooldown_minutes BETWEEN 5 AND 1440),
    alert_email_enabled boolean NOT NULL DEFAULT false,
    alert_email_min_severity varchar(16) NOT NULL DEFAULT 'critical' CHECK (alert_email_min_severity IN ('warning','critical')),
    retention_days integer NOT NULL DEFAULT 180 CHECK (retention_days BETWEEN 1 AND 3650),
    config_hash char(64), published_at timestamptz,
    created_by bigint REFERENCES users(id) ON DELETE SET NULL, updated_by bigint REFERENCES users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (monitor_id, revision), UNIQUE (id, monitor_id),
    CHECK (state = 'draft' AND config_hash IS NULL AND published_at IS NULL OR state = ANY (ARRAY['published','superseded']) AND config_hash IS NOT NULL AND published_at IS NOT NULL)
);
CREATE UNIQUE INDEX IF NOT EXISTS monitor_config_versions_one_draft_uq ON monitor_config_versions(monitor_id) WHERE state = 'draft';
CREATE UNIQUE INDEX IF NOT EXISTS monitor_config_versions_one_published_uq ON monitor_config_versions(monitor_id) WHERE state = 'published';

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'monitors_draft_config_version_fkey'
          AND conrelid = 'monitors'::regclass
    ) THEN
        ALTER TABLE monitors
            ADD CONSTRAINT monitors_draft_config_version_fkey
            FOREIGN KEY (draft_config_version_id) REFERENCES monitor_config_versions(id) ON DELETE RESTRICT;
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'monitors_published_config_version_fkey'
          AND conrelid = 'monitors'::regclass
    ) THEN
        ALTER TABLE monitors
            ADD CONSTRAINT monitors_published_config_version_fkey
            FOREIGN KEY (published_config_version_id) REFERENCES monitor_config_versions(id) ON DELETE RESTRICT;
    END IF;
END;
$$;

