CREATE OR REPLACE FUNCTION project_notification_event()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    projected_event_type varchar(32);
    projected_resource_type varchar(24);
    projected_resource_id bigint;
    projected_audience_role varchar(16);
    projected_occurred_at timestamptz;
    projected_payload jsonb;
    projected_dedupe_key varchar(160);
    alert_occurrence_count bigint;
    alert_state varchar(16);
    alert_cooldown_until timestamptz;
BEGIN
    IF TG_TABLE_NAME = 'event_updates' THEN
        projected_event_type := 'event.updated';
        projected_resource_type := 'event';
        projected_resource_id := NEW.event_id;
        projected_audience_role := 'viewer';
        projected_occurred_at := NEW.observed_at;
        projected_payload := jsonb_build_object(
            'title', '事件发生重要变化',
            'summary', NEW.summary,
            'status', NEW.kind
        );
        projected_dedupe_key := 'event_update:' || NEW.id;
    ELSIF TG_TABLE_NAME = 'alert_occurrences' THEN
        SELECT occurrence_count, state, cooldown_until
        INTO alert_occurrence_count, alert_state, alert_cooldown_until
        FROM alert_threads
        WHERE id = NEW.alert_thread_id;

        -- The first occurrence always disturbs. Later occurrences are durable
        -- facts but do not create a real-time notification while the thread is
        -- suppressed or still inside its frozen cooldown window.
        IF alert_occurrence_count > 0 AND (
            alert_state = 'suppressed' OR NEW.triggered_at < alert_cooldown_until
        ) THEN
            RETURN NEW;
        END IF;
        projected_event_type := 'alert.triggered';
        projected_resource_type := 'alert';
        projected_resource_id := NEW.alert_thread_id;
        projected_audience_role := 'viewer';
        projected_occurred_at := NEW.triggered_at;
        projected_payload := jsonb_build_object(
            'title', '触发新的热点告警',
            'severity', NEW.severity
        );
        projected_dedupe_key := 'alert_occurrence:' || NEW.id;
    ELSIF TG_TABLE_NAME = 'reports' THEN
        projected_event_type := CASE NEW.status WHEN 'published' THEN 'report.published' ELSE 'report.failed' END;
        projected_resource_type := 'report';
        projected_resource_id := NEW.id;
        projected_audience_role := CASE NEW.status WHEN 'published' THEN 'viewer' ELSE 'admin' END;
        projected_occurred_at := COALESCE(NEW.published_at, NEW.updated_at);
        projected_payload := jsonb_build_object(
            'title', CASE NEW.status WHEN 'published' THEN '报告已发布' ELSE '报告生成失败' END,
            'summary', left(NEW.title, 500),
            'status', NEW.status
        );
        projected_dedupe_key := 'report:' || NEW.id || ':' || NEW.status || ':' || NEW.version;
    ELSIF TG_TABLE_NAME = 'collection_runs' THEN
        projected_event_type := CASE NEW.status WHEN 'succeeded' THEN 'collection.succeeded' ELSE 'collection.failed' END;
        projected_resource_type := 'collection_run';
        projected_resource_id := NEW.id;
        projected_audience_role := CASE NEW.status WHEN 'succeeded' THEN 'editor' ELSE 'admin' END;
        projected_occurred_at := COALESCE(NEW.finished_at, NEW.updated_at);
        projected_payload := jsonb_build_object(
            'title', CASE NEW.status WHEN 'succeeded' THEN '采集任务已完成' ELSE '采集任务失败' END,
            'status', NEW.status
        );
        projected_dedupe_key := 'collection_run:' || NEW.id || ':' || NEW.status;
    ELSE
        RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'unsupported notification projection source';
    END IF;

    INSERT INTO notification_events (
        event_type, resource_type, resource_id, audience_role, occurred_at, payload, dedupe_key
    ) VALUES (
        projected_event_type, projected_resource_type, projected_resource_id,
        projected_audience_role, projected_occurred_at, projected_payload, projected_dedupe_key
    ) ON CONFLICT (dedupe_key) DO NOTHING;
    RETURN NEW;
END;
$$;

