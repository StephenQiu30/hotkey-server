CREATE TABLE IF NOT EXISTS document_version_embeddings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_version_id bigint NOT NULL REFERENCES document_versions(id) ON DELETE RESTRICT,
    source_connection_id bigint NOT NULL REFERENCES source_connections(id) ON DELETE RESTRICT,
    embed_local_rights_decision_id bigint NOT NULL,
    retain_rights_decision_id bigint NOT NULL,
    embed_action varchar(32) NOT NULL DEFAULT 'embed_local' CHECK (embed_action = 'embed_local'),
    embed_decision varchar(8) NOT NULL DEFAULT 'allow' CHECK (embed_decision = 'allow'),
    retain_action varchar(32) NOT NULL DEFAULT 'retain' CHECK (retain_action = 'retain'),
    retain_decision varchar(8) NOT NULL DEFAULT 'allow' CHECK (retain_decision = 'allow'),
    model_profile_id bigint NOT NULL REFERENCES ai_model_profiles(id) ON DELETE RESTRICT,
    model_profile_version bigint NOT NULL CHECK (model_profile_version > 0),
    model_version varchar(64) NOT NULL CHECK (model_version ~ '^[a-z0-9][a-z0-9._:-]{0,63}$'),
    normalized_text_sha256 char(64) NOT NULL CHECK (normalized_text_sha256 ~ '^[0-9a-f]{64}$'),
    embedding halfvec(1024),
    ai_run_id bigint NOT NULL REFERENCES ai_runs(id) ON DELETE RESTRICT,
    retention_until timestamptz NOT NULL,
    lifecycle_state varchar(16) NOT NULL DEFAULT 'active' CHECK (lifecycle_state IN ('active','tombstoned')),
    tombstoned_at timestamptz,
    purge_reason varchar(64),
    created_at timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (embed_local_rights_decision_id, source_connection_id, embed_action, embed_decision)
        REFERENCES source_rights_decisions(id, source_connection_id, action, decision) ON DELETE RESTRICT,
    FOREIGN KEY (retain_rights_decision_id, source_connection_id, retain_action, retain_decision)
        REFERENCES source_rights_decisions(id, source_connection_id, action, decision) ON DELETE RESTRICT,
    UNIQUE (document_version_id, model_profile_id, model_profile_version, model_version, normalized_text_sha256),
    CHECK (retention_until > created_at),
    CHECK (
        lifecycle_state = 'active' AND embedding IS NOT NULL AND tombstoned_at IS NULL AND purge_reason IS NULL
        OR lifecycle_state = 'tombstoned' AND embedding IS NULL AND tombstoned_at IS NOT NULL AND purge_reason IS NOT NULL
    )
);
CREATE INDEX IF NOT EXISTS document_version_embeddings_hnsw_idx
    ON document_version_embeddings USING hnsw (embedding halfvec_cosine_ops)
    WHERE lifecycle_state = 'active';

CREATE OR REPLACE FUNCTION enforce_compiled_profile_build()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    monitor_version_state text;
    preview_run_kind text;
    preview_run_status text;
    embedding_count integer;
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'monitor_compiled_profiles_retained',
            MESSAGE = 'compiled profiles are retained';
    END IF;
    IF TG_OP = 'INSERT' AND NEW.status <> 'building' THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'monitor_compiled_profiles_initial_building',
            MESSAGE = 'compiled profiles must be created in building state';
    END IF;
    IF TG_OP = 'UPDATE' AND OLD.status = 'retired' THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'monitor_compiled_profiles_immutable',
            MESSAGE = 'retired compiled profiles are immutable';
    END IF;
    IF TG_OP = 'UPDATE' AND (
        NEW.id IS DISTINCT FROM OLD.id OR NEW.version IS DISTINCT FROM OLD.version
        OR NEW.monitor_id IS DISTINCT FROM OLD.monitor_id
        OR NEW.purpose IS DISTINCT FROM OLD.purpose
        OR NEW.config_version_id IS DISTINCT FROM OLD.config_version_id
        OR NEW.monitor_version_id IS DISTINCT FROM OLD.monitor_version_id
        OR NEW.preview_run_id IS DISTINCT FROM OLD.preview_run_id
        OR NEW.draft_id IS DISTINCT FROM OLD.draft_id
        OR NEW.draft_resource_version IS DISTINCT FROM OLD.draft_resource_version
        OR NEW.intent_revision_id IS DISTINCT FROM OLD.intent_revision_id
        OR NEW.compiler_version IS DISTINCT FROM OLD.compiler_version
        OR NEW.matching_algorithm_version IS DISTINCT FROM OLD.matching_algorithm_version
        OR NEW.lexical_algorithm_version IS DISTINCT FROM OLD.lexical_algorithm_version
        OR NEW.semantic_algorithm_version IS DISTINCT FROM OLD.semantic_algorithm_version
        OR NEW.structured_algorithm_version IS DISTINCT FROM OLD.structured_algorithm_version
        OR NEW.search_normalization_profile_version IS DISTINCT FROM OLD.search_normalization_profile_version
        OR NEW.semantic_state IS DISTINCT FROM OLD.semantic_state
        OR NEW.semantic_unavailable_reason IS DISTINCT FROM OLD.semantic_unavailable_reason
        OR NEW.created_at IS DISTINCT FROM OLD.created_at
        OR OLD.status = 'building' AND NEW.status NOT IN ('building','ready')
        OR OLD.status = 'ready' AND (
            NEW.status <> 'retired'
            OR NEW.profile_hash IS DISTINCT FROM OLD.profile_hash
            OR NEW.ready_at IS DISTINCT FROM OLD.ready_at
            OR NEW.retired_at IS NULL
        )
    ) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'monitor_compiled_profiles_identity_immutable',
            MESSAGE = 'compiled profile identity and algorithms are immutable';
    END IF;
    IF NEW.status = 'ready' THEN
        SELECT state INTO monitor_version_state FROM monitor_config_versions
        WHERE id = NEW.config_version_id AND monitor_id = NEW.monitor_id FOR KEY SHARE;
        SELECT count(*) INTO embedding_count FROM monitor_compiled_intent_embeddings
        WHERE compiled_profile_id = NEW.id AND config_version_id = NEW.config_version_id;
        IF NEW.purpose = 'preview' THEN
            SELECT kind,status INTO preview_run_kind,preview_run_status
            FROM monitor_intent_analysis_runs
            WHERE id = NEW.preview_run_id AND monitor_id = NEW.monitor_id
              AND draft_id = NEW.draft_id AND draft_resource_version = NEW.draft_resource_version
            FOR KEY SHARE;
        END IF;
        IF NEW.semantic_state = 'ready' AND embedding_count <> 1
           OR NEW.semantic_state = 'unavailable' AND embedding_count <> 0
           OR NEW.purpose = 'published' AND monitor_version_state IS DISTINCT FROM 'published'
           OR NEW.purpose = 'preview' AND (
               monitor_version_state IS DISTINCT FROM 'draft'
               OR preview_run_kind IS DISTINCT FROM 'preview'
               OR preview_run_status NOT IN ('running','succeeded')
           )
        THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'monitor_compiled_profiles_ready_complete',
                MESSAGE = 'ready compiled profile requires its exact owner, intent revision and semantic state receipt';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS monitor_compiled_profiles_build ON monitor_compiled_profiles;
CREATE TRIGGER monitor_compiled_profiles_build
BEFORE INSERT OR UPDATE OR DELETE ON monitor_compiled_profiles
FOR EACH ROW EXECUTE FUNCTION enforce_compiled_profile_build();

CREATE OR REPLACE FUNCTION enforce_compiled_profile_child_append()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    profile_status text;
    profile_config_version_id bigint;
    profile_semantic_state text;
    model_record ai_model_profiles%ROWTYPE;
    run_record ai_runs%ROWTYPE;
BEGIN
    IF TG_OP <> 'INSERT' THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'monitor_compiled_profile_facts_append_only',
            MESSAGE = 'compiled profile facts are append-only';
    END IF;
    SELECT status,config_version_id,semantic_state
    INTO profile_status,profile_config_version_id,profile_semantic_state FROM monitor_compiled_profiles
    WHERE id = NEW.compiled_profile_id FOR KEY SHARE;
    IF profile_status IS DISTINCT FROM 'building' THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'monitor_compiled_profile_facts_building_only',
            MESSAGE = 'compiled profile facts may only be added while building';
    END IF;
    IF TG_TABLE_NAME = 'monitor_compiled_intent_embeddings' THEN
        SELECT * INTO model_record FROM ai_model_profiles WHERE id = NEW.model_profile_id FOR KEY SHARE;
        SELECT * INTO run_record FROM ai_runs WHERE id = NEW.ai_run_id FOR KEY SHARE;
        IF profile_semantic_state IS DISTINCT FROM 'ready'
           OR profile_config_version_id IS DISTINCT FROM NEW.config_version_id
           OR model_record.version IS DISTINCT FROM NEW.model_profile_version
           OR model_record.model_version IS DISTINCT FROM NEW.model_version
           OR model_record.task_type IS DISTINCT FROM 'embedding'
           OR model_record.embedding_dimensions IS DISTINCT FROM 1024
           OR run_record.status IS DISTINCT FROM 'succeeded'
           OR run_record.task_type IS DISTINCT FROM 'embedding'
           OR run_record.target_type IS DISTINCT FROM 'monitor_compiled_profile'
           OR run_record.target_id IS DISTINCT FROM NEW.compiled_profile_id
           OR run_record.model_profile_id IS DISTINCT FROM NEW.model_profile_id
           OR run_record.model_profile_version IS DISTINCT FROM NEW.model_profile_version
           OR run_record.model_version IS DISTINCT FROM NEW.model_version
           OR run_record.input_hash IS DISTINCT FROM NEW.input_hash
        THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'monitor_compiled_intent_embeddings_exact_run',
                MESSAGE = 'compiled intent embedding requires its exact succeeded model run';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
