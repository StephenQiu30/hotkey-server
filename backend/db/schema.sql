        REFERENCES source_rights_decisions(id, source_connection_id, action, decision) ON DELETE RESTRICT,
    UNIQUE (document_version_id, normalization_profile_version, normalized_text_sha256),
    CHECK (rights_action = 'store_derived' AND rights_decision = 'allow'),
    CHECK (retain_action = 'retain' AND retain_decision = 'allow'),
    CHECK (retention_until > indexed_at),
    CHECK (
        lifecycle_state = 'active'
          AND title_search_vector IS NOT NULL AND body_search_vector IS NOT NULL
