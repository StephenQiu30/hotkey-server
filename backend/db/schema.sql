    document_content_sha256 char(64);
    document_captured_at timestamptz;
    retained_days integer;
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'derived_artifacts_retained', MESSAGE = 'derived artifacts cannot be deleted';
    END IF;
    IF NEW.document_version_id IS DISTINCT FROM OLD.document_version_id
       OR NEW.source_connection_id IS DISTINCT FROM OLD.source_connection_id
       OR NEW.store_derived_rights_decision_id IS DISTINCT FROM OLD.store_derived_rights_decision_id
       OR NEW.retain_rights_decision_id IS DISTINCT FROM OLD.retain_rights_decision_id
       OR NEW.rights_action IS DISTINCT FROM OLD.rights_action
       OR NEW.rights_decision IS DISTINCT FROM OLD.rights_decision
       OR NEW.retain_action IS DISTINCT FROM OLD.retain_action
       OR NEW.retain_decision IS DISTINCT FROM OLD.retain_decision
       OR NEW.artifact_type IS DISTINCT FROM OLD.artifact_type
       OR NEW.transformer_profile_sha256 IS DISTINCT FROM OLD.transformer_profile_sha256
       OR NEW.vault_relative_path IS DISTINCT FROM OLD.vault_relative_path
       OR NEW.mime_type IS DISTINCT FROM OLD.mime_type
       OR NEW.sha256 IS DISTINCT FROM OLD.sha256
       OR NEW.size_bytes IS DISTINCT FROM OLD.size_bytes
       OR NEW.retention_until IS DISTINCT FROM OLD.retention_until
       OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'derived_artifacts_identity_immutable', MESSAGE = 'derived artifact identity is immutable';
    END IF;
    IF NEW.lifecycle_state IN ('derive_pending','derived_available') THEN
        SELECT content_sha256, captured_at
        INTO document_content_sha256, document_captured_at
        FROM document_versions WHERE id = NEW.document_version_id;
        retained_days := current_rights_retention_days(
            NEW.source_connection_id, 'document_version', NEW.document_version_id::text,
            document_content_sha256, CURRENT_TIMESTAMP
        );
        IF document_content_sha256 IS NULL
           OR NOT current_rights_action_is_allowed(
               NEW.source_connection_id, 'document_version', NEW.document_version_id::text,
               document_content_sha256, 'store_derived', CURRENT_TIMESTAMP
           )
           OR retained_days IS NULL
           OR NEW.retention_until > document_captured_at + retained_days * interval '24 hours'
           OR NEW.retention_until <= CURRENT_TIMESTAMP THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'derived_artifacts_current_rights_gate', MESSAGE = 'derived artifact lifecycle requires current store_derived and retain allows';
        END IF;
    END IF;
    IF NOT (
        OLD.lifecycle_state = NEW.lifecycle_state
        OR OLD.lifecycle_state = 'derive_pending' AND NEW.lifecycle_state IN ('derived_available','derive_failed','quarantined')
        OR OLD.lifecycle_state = 'derive_failed' AND NEW.lifecycle_state IN ('derive_pending','quarantined','tombstoned')
        OR OLD.lifecycle_state = 'derived_available' AND NEW.lifecycle_state IN ('retention_blocked','quarantined','tombstoned')
        OR OLD.lifecycle_state IN ('retention_blocked','quarantined') AND NEW.lifecycle_state = 'tombstoned'
    ) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'derived_artifacts_lifecycle_transition', MESSAGE = 'invalid derived artifact lifecycle transition';
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS derived_artifacts_lifecycle ON derived_artifacts;
