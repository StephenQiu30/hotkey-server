CREATE OR REPLACE FUNCTION enforce_source_rights_decision_batch_policy()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    policy_record source_rights_policies%ROWTYPE;
BEGIN
    SELECT * INTO policy_record FROM source_rights_policies WHERE id = NEW.policy_id;
    IF NOT FOUND OR policy_record.version IS DISTINCT FROM NEW.expected_policy_version THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'source_rights_decision_batches_policy_binding',
            MESSAGE = 'rights decision batch policy version is missing or changed';
    END IF;
    IF policy_record.scope_type <> 'organization_default'
       AND policy_record.source_connection_id IS DISTINCT FROM NEW.source_connection_id THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'source_rights_decision_batches_policy_source',
            MESSAGE = 'rights decision batch source does not match policy source';
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS source_rights_decision_batches_policy_binding ON source_rights_decision_batches;
CREATE TRIGGER source_rights_decision_batches_policy_binding
BEFORE INSERT ON source_rights_decision_batches
FOR EACH ROW EXECUTE FUNCTION enforce_source_rights_decision_batch_policy();

CREATE OR REPLACE FUNCTION enforce_source_rights_decision_policy()
