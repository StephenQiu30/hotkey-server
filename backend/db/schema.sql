    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint NOT NULL DEFAULT 1 CHECK (version = 1),
    document_version_id bigint NOT NULL REFERENCES document_versions(id) ON DELETE RESTRICT,
    source_connection_id bigint NOT NULL REFERENCES source_connections(id) ON DELETE RESTRICT,
    derived_artifact_id bigint NOT NULL REFERENCES derived_artifacts(id) ON DELETE RESTRICT,
    store_derived_rights_decision_id bigint NOT NULL,
    retain_rights_decision_id bigint NOT NULL,
    rights_action varchar(32) NOT NULL DEFAULT 'store_derived',
    rights_decision varchar(8) NOT NULL DEFAULT 'allow',
    retain_action varchar(32) NOT NULL DEFAULT 'retain',
    retain_decision varchar(8) NOT NULL DEFAULT 'allow',
    normalization_profile_version varchar(64) NOT NULL CHECK (normalization_profile_version ~ '^[a-z0-9][a-z0-9._:-]{0,63}$'),
    normalized_text_sha256 char(64) NOT NULL CHECK (normalized_text_sha256 ~ '^[0-9a-f]{64}$'),
    title_search_vector tsvector,
    body_search_vector tsvector,
    title_trigrams text[],
    body_trigrams text[],
    entity_keys text[],
    action_keys text[],
    location_keys text[],
    region_keys text[],
    lifecycle_state varchar(16) NOT NULL DEFAULT 'active' CHECK (lifecycle_state IN ('active','tombstoned')),
    tombstoned_at timestamptz,
    purge_reason varchar(64),
